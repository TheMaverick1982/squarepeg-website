//
// This endpoint writes a row and nothing else. Nothing a member of the public
// submits is ever shown on squarepegpizzeria.com: entries go to the kitchen,
// we pick one, it runs as an LTO. There is no path through this function that
// publishes anything, and no API that reads these rows back out.
//
// Only two fields are free text -- what they called it and who built it -- and
// both are read by a person before they go anywhere. Everything else is checked
// against the same fixed list the page offers, generated from data/labs.py by
// `python3 tools/lab_allowlist.py --write`, so a crafted request cannot smuggle
// free text into what looks like a structured field, and the lists cannot drift
// from the kitchen.
