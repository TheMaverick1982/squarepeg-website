const ORIGINS = (Deno.env.get("ALLOWED_ORIGINS") ?? "").split(",").map((s) => s.trim()).filter(Boolean);

function cors(origin: string | null) {
  const allow = !ORIGINS.length || (origin && ORIGINS.includes(origin)) ? (origin ?? "*") : ORIGINS[0];
  return {
    "Access-Control-Allow-Origin": allow,
    "Access-Control-Allow-Headers": "content-type",
    "Access-Control-Allow-Methods": "POST, OPTIONS",
    "Vary": "Origin",
  };
}

const str = (v: unknown, max: number) => (typeof v === "string" ? v.trim().slice(0, max) : "");

// Same fail-open posture as the contact form: we only turn someone away when
// Cloudflare actively says the token is bad. Unset the secret to disable.
async function humanCheck(token: string, ip: string): Promise<boolean> {
  const secret = Deno.env.get("TURNSTILE_SECRET_KEY");
  if (!secret || !token) return true;
  try {
    const body = new FormData();
    body.append("secret", secret);
    body.append("response", token);
    if (ip) body.append("remoteip", ip);
    const r = await fetch("https://challenges.cloudflare.com/turnstile/v0/siteverify", {
      method: "POST", body, signal: AbortSignal.timeout(4000),
    });
    if (!r.ok) return true;
    return (await r.json())?.success === true;
  } catch {
    return true;
  }
}

type Pair = { label: string; value: string | string[] };

// Walk the bench's groups in the order the page shows them and build the
// ordered label/value list that gets stored. Returns null the moment anything
// is not on our own list, which is the only reason a well-formed build is ever
// turned away.
function readBuild(bench: Bench, body: Record<string, unknown>): Pair[] | null {
  const out: Pair[] = [];
  for (const g of bench.groups) {
    const raw = body[g.field];
    if (g.pick === "many") {
      const vs = (Array.isArray(raw) ? raw : [])
        .filter((x): x is string => typeof x === "string")
        .map((x) => x.trim().slice(0, 60));
      if (!vs.length) {
        if (!g.optional) return null;
        continue;
      }
      if (vs.length > g.max) return null;
      if (new Set(vs).size !== vs.length) return null;
      if (!vs.every((v) => g.options.includes(v))) return null;
      out.push({ label: g.label, value: vs });
    } else {
      const v = str(raw, 60);
      if (!v) {
        if (!g.optional) return null;
        continue;
      }
      if (!g.options.includes(v)) return null;
      out.push({ label: g.label, value: v });
    }
  }
  return out;
}

Deno.serve(async (req) => {
  const origin = req.headers.get("origin");
  const headers = { ...cors(origin), "Content-Type": "application/json" };
  if (req.method === "OPTIONS") return new Response("ok", { headers: cors(origin) });
  if (req.method !== "POST") {
    return new Response(JSON.stringify({ error: "POST only" }), { status: 405, headers });
  }
  if (ORIGINS.length && origin && !ORIGINS.includes(origin)) {
    return new Response(JSON.stringify({ error: "forbidden" }), { status: 403, headers });
  }

  const b = await req.json().catch(() => null);
  if (!b) return new Response(JSON.stringify({ error: "bad request" }), { status: 400, headers });

  const ip = (req.headers.get("x-forwarded-for") ?? "").split(",")[0].trim();
  if (!(await humanCheck(str(b.turnstile_token, 2048), ip))) {
    return new Response(JSON.stringify({ error: "could not verify" }), { status: 400, headers });
  }

  // No kind means the Pizza Lab. That is what the page sent before there were
  // five benches, and it is still what it sends, so this must never change.
  const kind = str(b.kind, 40) || "pizza-lab";
  const bench = BENCHES[kind];
  if (!bench) {
    return new Response(JSON.stringify({ error: "unknown bench" }), { status: 400, headers });
  }

  const name = str(b.name, 40);
  const by = str(b.by, 40);
  const build = name ? readBuild(bench, b as Record<string, unknown>) : null;
  if (!build) {
    return new Response(
      JSON.stringify({ error: `that isn't a ${bench.unit} we can make` }),
      { status: 400, headers },
    );
  }

  // status defaults to 'pending' in the schema and is deliberately not settable
  // from here. It is only ever changed by hand, and only to keep the inbox
  // short -- it does not control whether anything is shown, because nothing is.
  const row: Record<string, unknown> = { kind, name, by_name: by || null, build };

  // The pizza also writes the four original columns. They predate `build` and
  // the back catalogue, the inbox view and anything else built on them stay
  // whole if new pizzas keep filling them in.
  if (kind === "pizza-lab") {
    row.sauce = str(b.sauce, 60);
    row.cheese = str(b.cheese, 60);
    row.toppings = (Array.isArray(b.toppings) ? b.toppings : [])
      .filter((t: unknown): t is string => typeof t === "string")
      .map((t: string) => t.trim().slice(0, 60));
    row.finish = str(b.finish, 60) || null;
  }

  const db = createClient(
    Deno.env.get("SUPABASE_URL") ?? "",
    Deno.env.get("SUPABASE_SERVICE_ROLE_KEY") ?? "",
    { auth: { persistSession: false } },
  );

  const { error } = await db.from("lab_entries").insert(row);
  if (error) {
    return new Response(JSON.stringify({ error: "could not save" }), { status: 500, headers });
  }
  return new Response(JSON.stringify({ ok: true }), { headers });
});
