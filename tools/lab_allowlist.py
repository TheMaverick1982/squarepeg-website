"""Print the allow-lists lab-submit needs, generated from data/labs.py.

The edge function validates every value against its own copy of the lists and
rejects anything it does not recognise. That copy has to match the site's
exactly or entries bounce, so it is generated rather than retyped: run this,
paste the output into the function, deploy.

    python3 tools/lab_allowlist.py          # the three new labs
    python3 tools/lab_allowlist.py --all    # including the pizza

The pizza is left out by default because its lists are already deployed and
nothing about them changed.

Run from the site root.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "data"))
from labs import BUILDERS  # noqa: E402


def fields(b):
    for g in b["groups"]:
        opts = ([o for _, xs in g["sections"] for o in xs]
                if "sections" in g else g["options"])
        yield g.get("field", g["key"]), g["pick"], g.get("max", 0), opts


def main():
    want_all = "--all" in sys.argv
    print("// Generated by tools/lab_allowlist.py from data/labs.py.")
    print("// Do not hand-edit: regenerate when the kitchen lists change.")
    print("const LABS: Record<string, Record<string, string[]>> = {")
    for b in BUILDERS:
        if b["slug"] == "pizza-lab" and not want_all:
            continue
        print('  "%s": {' % b["slug"])
        for field, pick, mx, opts in fields(b):
            items = [json.dumps(o, ensure_ascii=False) for o in opts]
            line = '    %s: [%s],' % (json.dumps(field), ", ".join(items))
            if len(line) <= 96:
                print(line)
                continue
            # Wrap BETWEEN items, never inside one. textwrap breaks on any
            # space, which splits "Fig jam" across two lines and produces
            # TypeScript that does not compile.
            print('    %s: [' % json.dumps(field))
            row = []
            for it in items:
                if row and len("      " + ", ".join(row + [it])) > 92:
                    print("      " + ", ".join(row) + ",")
                    row = []
                row.append(it)
            if row:
                print("      " + ", ".join(row))
            print("    ],")
        print("  },")
    print("};")
    print()
    print("// Which fields are lists rather than single values, and their caps.")
    print("const MULTI: Record<string, Record<string, number>> = {")
    for b in BUILDERS:
        if b["slug"] == "pizza-lab" and not want_all:
            continue
        many = {f: mx for f, pick, mx, _ in fields(b) if pick == "many"}
        print('  "%s": %s,' % (b["slug"], json.dumps(many)))
    print("};")


if __name__ == "__main__":
    main()
