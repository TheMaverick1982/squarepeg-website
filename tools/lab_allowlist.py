"""Print the bench definitions lab-submit needs, generated from data/labs.py.

The edge function validates every value against its own copy of these lists
and rejects anything it does not recognise, so that copy has to match the
site's exactly or entries bounce. It is generated rather than retyped.

It also carries each group's label and order, because the function stores the
build as an ordered list of label/value pairs. That is what lets the weekly
email and the Google Sheet render a drink and a pizza with the same code and
no idea what either one is.

    python3 tools/lab_allowlist.py            # print it
    python3 tools/lab_allowlist.py --write    # paste it into the function

Run from the site root.
"""
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent / "data"))
from labs import BUILDERS  # noqa: E402

START = "// BENCHES-START"
END = "// BENCHES-END"
FN = pathlib.Path("supabase/functions/lab-submit/index.ts")


def groups(b):
    for g in b["groups"]:
        opts = ([o for _, xs in g["sections"] for o in xs]
                if "sections" in g else g["options"])
        yield {
            "key": g["key"],
            "field": g.get("field", g["key"]),
            "label": g["legend"],
            "pick": g["pick"],
            "max": g.get("max", 0),
            # "a missing value is acceptable" -- either the group is
            # genuinely optional, or the page pre-checks a default, so an
            # empty one means an odd client rather than a bad build.
            "optional": bool(g.get("optional") or g.get("default")),
            "options": opts,
        }


def render():
    out = [START,
           "// Generated by tools/lab_allowlist.py from data/labs.py.",
           "// Do not hand-edit: regenerate when the kitchen lists change.",
           "const BENCHES: Record<string, Bench> = {"]
    for b in BUILDERS:
        out.append('  "%s": {' % b["slug"])
        out.append('    unit: %s,' % json.dumps(b["unit"]))
        out.append("    groups: [")
        for g in groups(b):
            head = ('      { key: %s, field: %s, label: %s, pick: %s, max: %d, optional: %s,'
                    % (json.dumps(g["key"]), json.dumps(g["field"]),
                       json.dumps(g["label"], ensure_ascii=False),
                       json.dumps(g["pick"]), g["max"],
                       "true" if g["optional"] else "false"))
            out.append(head)
            items = [json.dumps(o, ensure_ascii=False) for o in g["options"]]
            one = "        options: [%s] }," % ", ".join(items)
            if len(one) <= 96:
                out.append(one)
                continue
            # Wrap BETWEEN items, never inside one: textwrap breaks on any
            # space, which splits "Fig jam" across two lines and produces
            # TypeScript that does not compile.
            out.append("        options: [")
            row = []
            for it in items:
                if row and len("          " + ", ".join(row + [it])) > 94:
                    out.append("          " + ", ".join(row) + ",")
                    row = []
                row.append(it)
            if row:
                out.append("          " + ", ".join(row))
            out.append("        ] },")
        out.append("    ],")
        out.append("  },")
    out.append("};")
    out.append(END)
    return "\n".join(out)


def main():
    block = render()
    if "--write" not in sys.argv:
        print(block)
        return 0
    s = FN.read_text(encoding="utf-8")
    if START not in s or END not in s:
        sys.exit("%s has no %s / %s markers" % (FN, START, END))
    head, rest = s.split(START, 1)
    _, tail = rest.split(END, 1)
    FN.write_text(head + block + tail, encoding="utf-8")
    print("wrote the benches into", FN)
    return 0


if __name__ == "__main__":
    sys.exit(main())
